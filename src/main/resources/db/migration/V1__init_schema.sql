-- ApexChat initial schema. Portable across PostgreSQL 16 and H2 (PostgreSQL mode).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(32)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE chat_room (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(40)  NOT NULL UNIQUE,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(200),
    created_by  VARCHAR(32)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE chat_message (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id   BIGINT REFERENCES chat_room (id) ON DELETE CASCADE,
    sender    VARCHAR(32)   NOT NULL,
    recipient VARCHAR(32),
    content   VARCHAR(2000) NOT NULL,
    sent_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- a message targets exactly one room OR exactly one recipient
    CONSTRAINT chk_message_target CHECK ((room_id IS NULL) <> (recipient IS NULL))
);

-- Keyset pagination: WHERE room_id = ? AND id < ? ORDER BY id DESC
CREATE INDEX idx_message_room_id ON chat_message (room_id, id);
-- Direct conversations are looked up from both directions
CREATE INDEX idx_message_dm ON chat_message (sender, recipient, id);

